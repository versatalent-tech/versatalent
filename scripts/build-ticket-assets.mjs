/**
 * Turns the ticket design (src/lib/tickets/template/ticket-template.pdf) and
 * the logo (public/images/versatalent-new-logo.png) into a module the PDF
 * builder can import, so the serverless functions don't need to read files.
 * Run after changing either: node scripts/build-ticket-assets.mjs
 */
import fs from 'node:fs';
import sharp from 'sharp';

const dir = 'src/lib/tickets/template';
const template = fs.readFileSync(`${dir}/ticket-template.pdf`);

// The logo cropped to its ink (with a little room), in the original dark and in white for dark backgrounds
const source = sharp('public/images/versatalent-new-logo.png');
const { data, info } = await source.clone().raw().toBuffer({ resolveWithObject: true });
let [minX, minY, maxX, maxY] = [info.width, info.height, 0, 0];
for (let y = 0; y < info.height; y++) {
  for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 40) {
      minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
  }
}
const side = Math.max(maxX - minX, maxY - minY) + 16;
const left = Math.max(0, Math.round((minX + maxX - side) / 2));
const top = Math.max(0, Math.round((minY + maxY - side) / 2));
const square = { left, top, width: Math.min(side, info.width - left), height: Math.min(side, info.height - top) };
const dark = await sharp('public/images/versatalent-new-logo.png').extract(square).resize(240, 240).png().toBuffer();
const white = await sharp('public/images/versatalent-new-logo.png')
  .extract(square)
  .resize(240, 240)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true })
  .then(({ data: px, info: i }) => {
    for (let p = 0; p < px.length; p += 4) px[p] = px[p + 1] = px[p + 2] = 255;
    return sharp(px, { raw: { width: i.width, height: i.height, channels: 4 } }).png().toBuffer();
  });

fs.writeFileSync(
  `${dir}/assets.ts`,
  `// Generated by scripts/build-ticket-assets.mjs - do not edit by hand.\n` +
    `export const TICKET_TEMPLATE_PDF = '${template.toString('base64')}';\n` +
    `export const LOGO_DARK_PNG = '${dark.toString('base64')}';\n` +
    `export const LOGO_WHITE_PNG = '${white.toString('base64')}';\n`
);
console.log('wrote', `${dir}/assets.ts`, { template: template.length, dark: dark.length, white: white.length });
